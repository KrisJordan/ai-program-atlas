def parse(html: str) -> dict:
    observed = parse_catalog(
        html,
        pid="cmu-bs-ai",
        title="Artificial Intelligence, B.S.",
        award="BS",
        kind="degree",
        source_url=SOURCES[0],
        sections={
            "Computer Science": "cs",
            "Artificial Intelligence": "ai",
            "Ethics Course": "ethics",
        },
    )

    return classify_observed(enrich_requirements(html, observed, SOURCES[0]))


