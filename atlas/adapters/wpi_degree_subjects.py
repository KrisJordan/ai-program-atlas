def observe(parser):
    @wraps(parser)
    def observed(*args, **kwargs):
        result = parser(*args, **kwargs)
        for course in result.get("courses", []):
            course["category"] = SUBJECTS.get((course.get("code"), course.get("name")), "other")
            course.pop("category_review", None)
        return result
    return observed
